# --> ПРОВЕРКА АРТЕФАКТА <--
# - собирает монолит из src/ во временный файл и сверяет с отгруженным: -
# - расхождение значит, что отгруженный файл правили руками, а не через модули -
# - файл выдачи eli.sh сверяется со сборкой тем же способом -
# - строка сборки (метка времени) при сверке игнорируется -
# -Usage: bash tools/verify.sh -
# -rc: 0 - артефакт и файл выдачи воспроизводятся из модулей, 1 - расхождение -
set -o pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
SHIPPED="${DIR}/the_vps_of_eli.sh"
DELIVERY="${DIR}/eli.sh"
TMP="$(mktemp)"

cleanup() { rm -f "$TMP"; }
trap cleanup EXIT

if ! ELI_BUILD_OUT="$TMP" bash "${DIR}/build.sh" >/dev/null 2>&1; then
    echo "проверка артефакта: сборка не прошла, смотри bash build.sh"
    exit 1
fi

FAIL=0

# --> ОТГРУЖЕННЫЙ МОНОЛИТ <--
if diff <(grep -v '^# Собран:' "$SHIPPED") <(grep -v '^# Собран:' "$TMP") >/dev/null 2>&1; then
    echo "артефакт воспроизводится из модулей: правок монолита в обход src/ нет"
else
    echo "РАСХОЖДЕНИЕ: отгруженный монолит отличается от сборки из src/"
    echo "--- строки, которые есть в собранном из src, но нет в отгруженном ---"
    diff <(grep -v '^# Собран:' "$SHIPPED") <(grep -v '^# Собран:' "$TMP") | grep '^>' | head -20
    echo "--- обратное ---"
    diff <(grep -v '^# Собран:' "$SHIPPED") <(grep -v '^# Собран:' "$TMP") | grep '^<' | head -20
    FAIL=1
fi

# --> ФАЙЛ ВЫДАЧИ <--
# - eli.sh заливается на сервер по инструкции: отставшая копия отдаёт сборку -
# - прошлых циклов, поэтому сверяется со сборкой из src/, а не с монолитом -
if [[ ! -f "$DELIVERY" ]]; then
    echo "РАСХОЖДЕНИЕ: файл выдачи отсутствует: ${DELIVERY}"
    FAIL=1
elif diff <(grep -v '^# Собран:' "$DELIVERY") <(grep -v '^# Собран:' "$TMP") >/dev/null 2>&1; then
    echo "файл выдачи eli.sh совпадает со сборкой из src/ (кроме строки сборки)"
else
    echo "РАСХОЖДЕНИЕ: eli.sh (файл выдачи) отличается от сборки из src/"
    echo "--- строки, которые есть в собранном из src, но нет в eli.sh ---"
    diff <(grep -v '^# Собран:' "$DELIVERY") <(grep -v '^# Собран:' "$TMP") | grep '^>' | head -20
    echo "--- обратное ---"
    diff <(grep -v '^# Собран:' "$DELIVERY") <(grep -v '^# Собран:' "$TMP") | grep '^<' | head -20
    echo "файл выдачи обновляется копированием монолита: cp the_vps_of_eli.sh eli.sh"
    FAIL=1
fi

exit "$FAIL"
